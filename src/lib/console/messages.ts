const catalog: Record<ConsoleLocale, Record<MessageKey, string>> = { ar, en };

export function message(key: MessageKey, locale: ConsoleLocale): string {
  return catalog[locale][key];
}

/**
 * The whole catalog in one language. A server page passes this to a client
 * component so the message map stays out of the browser bundle and every lookup
 * in that component is still a typed `MessageKey` rather than a free string.
 */
export function catalogFor(locale: ConsoleLocale): Record<MessageKey, string> {
  return catalog[locale];
}
