const SITE_ROOTS = ['src/app/[lang]/layout.tsx', 'src/components/pages/NotFoundDocument.tsx'];

describe('MB-1 the site paints the original site’s faces', () => {
  it('needs no network at build time', () => {
    const offenders = sourceFiles().filter((file) =>
      /from\s+['"]next\/font\/google['"]/.test(read(file)),
    );
    expect(offenders).toEqual([]);
    expect(fontsModule).toMatch(/from\s+["']next\/font\/local["']/);
    // …and the hand-declared faces point at this repo, not at a CDN.
    expect(siteFonts).not.toMatch(/https?:/);
    expect(siteFonts).not.toMatch(/fonts\.(googleapis|gstatic)\.com/);
  });

  it('declares the two families with the descriptors the reference compiled', () => {
    const subsets = FACES.filter((face) => face.file);
    expect(subsets.map((face) => face.family).sort()).toEqual([
      'Montserrat', 'Montserrat', 'Montserrat', 'Montserrat', 'Montserrat',
      'Readex Pro', 'Readex Pro', 'Readex Pro', 'Readex Pro',
    ]);
    // The reference’s variable ranges: Readex Pro has no 800/900 at all, so a
    // `font-black` request is synthesised there and here alike.
    for (const face of subsets.filter((f) => f.family === 'Readex Pro')) {
      expect(face.weight, 'Readex Pro is a 160–700 variable').toBe('160 700');
      expect(face.display).toBe('swap');
      expect(face.ranges, `${face.file} carries a unicode-range`).not.toBe('');
    }
    for (const face of subsets.filter((f) => f.family === 'Montserrat')) {
      expect(face.weight, 'Montserrat is a 100–900 variable').toBe('100 900');
      expect(face.display).toBe('swap');
      expect(face.ranges, `${face.file} carries a unicode-range`).not.toBe('');
    }
    // Two measured fallbacks, at the values the reference build measured off Arial.
    const fallbacks = FACES.filter((face) => !face.file);
    expect(fallbacks.map((face) => face.family).sort()).toEqual([
      'Montserrat Fallback', 'Readex Pro Fallback',
    ]);
    expect(fallbacks.find((f) => f.family === 'Readex Pro Fallback')?.sizeAdjust).toBe('108.34%');
    expect(fallbacks.find((f) => f.family === 'Montserrat Fallback')?.sizeAdjust).toBe('112.83%');
    for (const face of fallbacks) expect(face.block).toMatch(/src:\s*local\("Arial"\)/);
  });

  it('ships every binary it names, byte for byte', () => {
    const named = FACES.filter((face) => face.file).map((face) => face.file);
    expect(new Set(named).size, 'nine distinct subsets').toBe(9);
    expect(named.sort()).toEqual(Object.keys(SHIPPED).sort());
    for (const file of named) {
      const buffer = readBuffer(join('public/fonts', file));
      expect(buffer.subarray(0, 4).toString('latin1'), `${file} is woff2`).toBe('wOF2');
      // A silently truncated binary is the failure a text diff cannot see, and the
      // metrics behind "the same fonts" live inside these bytes.
      expect(
        createHash('sha256').update(buffer).digest('hex'),
        `${file} is the binary the reference shipped`,
      ).toBe(SHIPPED[file as keyof typeof SHIPPED]);
    }
    expect(readdirSync(join(process.cwd(), 'public/fonts')).sort()).toEqual(named.sort());
  });

  it('carries the license each binary travels under', () => {
    const licenses: [string, RegExp][] = [
      ['src/lib/fonts/OFL.txt', /Copyright.*Boutros/i],
      ['src/lib/fonts/OFL-Readex-Pro.txt', /Readex Pro Project Authors/i],
      ['src/lib/fonts/OFL-Montserrat.txt', /Montserrat/i],
    ];
    for (const [path, copyright] of licenses) {
      const ofl = read(path);
      expect(ofl, `${path} is the SIL OFL`).toMatch(/SIL Open Font License/i);
      expect(ofl, `${path} names its authors`).toMatch(copyright);
      expect(statSync(join(process.cwd(), path)).size).toBeGreaterThan(1000);
    }
  });

  it('paints one token, and picks the face by reading direction', () => {
    // The reference writes this split as `body` then `[dir="ltr"] body`; here the same
    // pair is one token, so no component has to know which face its page is in.
    expect(tokens).toMatch(/--font-ui:\s*var\(--font-readex-pro\);/);
    const ltr = /\[dir="ltr"\]\s*\{[^}]*\}/.exec(tokens)?.[0] ?? '';
    expect(ltr, 'LTR swaps the token, it does not add a second family rule').toMatch(
      /--font-ui:\s*var\(--font-montserrat\);/,
    );
    for (const family of ['Readex Pro', 'Montserrat']) {
      expect(tokens, `the stack names the declared ${family} first`).toMatch(
        new RegExp(`--font-[a-z-]+:\\s*"${family}",\\s*"${family} Fallback",\\s*"Segoe UI"`),
      );
    }
    for (const line of globals.split('\n').filter((l) => l.includes('font-family:'))) {
      expect(line.trim(), 'every site family declaration goes through the one token').toBe(
        'font-family: var(--font-ui);',
      );
    }
    // No site component may name a family either: the token is the only way to the
    // faces. The console tree is excluded because it owns its face on purpose —
    // `src/app/(console)/console/layout.tsx` applies `tajawal.variable` and the next
    // test is what proves that stays true.
    const named = sourceFiles()
      .filter((file) => file.endsWith('.tsx'))
      .filter((file) => !file.includes(join('(console)')))
      .filter((file) => /readex|montserrat|tajawal/i.test(withoutComments(read(file))));
    expect(named, 'site components ask for --font-ui, never for a family').toEqual([]);
  });

  it('keeps the console on its own face', () => {
    // The console reads `--c-font` or its own mono face, never the site’s `--font-ui`,
    // and its face is still generated from `src/lib/fonts`.
    for (const line of consoleCss.split('\n').filter((l) => l.includes('font-family:'))) {
      expect(line.trim(), 'the console paints one of its own families').toMatch(
        /^font-family: var\(--c-font(?:-mono)?[),]/,
      );
    }
    expect(consoleCss).toMatch(/--c-font:\s*var\(--font-tajawal\)/);
    const layout = read('src/app/(console)/console/layout.tsx');
    expect(layout).toMatch(/\$\{tajawal\.variable\}/);
  });

  it('reaches the faces from every document that paints site type', () => {
    // Declared in a stylesheet rather than generated per document, so the proof is the
    // import chain: globals.css carries the faces, and every site root imports globals.
    expect(globals).toMatch(/@import\s+["']\.\.\/styles\/fonts\.css["']/);
    for (const file of SITE_ROOTS) {
      expect(read(file), `${file} loads the site stylesheet`).toMatch(
        /import\s+["'][^"']*globals\.css["']/,
      );
      expect(read(file), `${file} no longer applies the console face`).not.toMatch(/tajawal/);
    }
  });

  it('keeps the scale in the base layer so a component can still name its own size', () => {
    // Unlayered rules outrank every Tailwind utility; an unlayered `h1 { font-size }`
    // would flatten `text-4xl md:text-6xl` into the scale instead of filling the gap.
    const base = layerBlock(globals, 'base');
    expect(base).not.toBe('');
    for (const token of ['--fs-h1', '--fs-h2', '--fs-h3', '--fs-h4', '--lh-tight']) {
      expect(tokens).toMatch(new RegExp(`\\s${token}:`));
    }
    expect(base).toMatch(/h1\s*\{\s*font-size:\s*var\(--fs-h1\);/);
    expect(base).toMatch(/h4\s*\{\s*font-size:\s*var\(--fs-h4\);/);
    expect(base).toMatch(/text-wrap:\s*balance/);
    expect(globals.indexOf('--fs-h1:')).toBeLessThan(globals.indexOf(base));
  });

  it('never tracks Arabic, in either direction', () => {
    // Arabic letters join, so tracking apart from them is a defect whatever its sign:
    // `-0.015em` separates the tooth from the join, `0.3em` dissolves the kashida.
    // The fix is one rule that flattens the scale in RTL, not a `[dir="rtl"]` twin at
    // each of the twelve places that used to ask for tracking by hand.
    const zeroing = /\[dir="rtl"\]\s*\{[^}]*\}/.exec(tokens)?.[0] ?? '';
    expect(zeroing, 'RTL has no tracked step').not.toBe('');
    for (const token of ['--ls-heading', '--ls-eyebrow', '--ls-label', '--ls-soft']) {
      expect(zeroing, `${token} resolves to nothing in Arabic`).toMatch(
        new RegExp(`${token}:\\s*0;`),
      );
    }
    // The heading rule asks for the token unqualified, because the token is what knows
    // which way the page runs.
    expect(layerBlock(globals, 'base')).toMatch(
      /h1,\s*h2\s*\{\s*letter-spacing:\s*var\(--ls-heading\);/,
    );
    // Tailwind’s own names route through the same tokens, so a component that writes
    // `tracking-tight` is asking for the house value and not for -0.025em.
    expect(globals).toMatch(/@theme\s*\{[^}]*--tracking-tight:\s*var\(--ls-heading\);/);
    expect(globals).toMatch(/--tracking-eyebrow:\s*var\(--ls-eyebrow\);/);
    // …and nothing in the tree still names a tracking value per call site.
    const literal = sourceFiles()
      .filter((file) => file.endsWith('.tsx'))
      .filter((file) => /tracking-\[/.test(read(file)));
    expect(literal).toEqual([]);
  });

  it('has no physical directional property in either stylesheet', () => {
    const physical =
      /(^|\s)(margin|padding)-(left|right):|text-align:\s*(left|right)|border-(left|right):/m;
    for (const [name, css] of [
      ['globals.css', globals],
      ['console.css', consoleCss],
    ] as const) {
      const hits = css.split('\n').filter((line) => physical.test(line));
      expect(hits, `${name} uses logical properties only`).toEqual([]);
    }
  });

  it('reserves a digit cell geometrically instead of asking for tnum', () => {
    // MB-1 measured the shipped binaries again, in Chromium, at the weights the call
    // sites use. The two faces disagree: Montserrat answers `tabular-nums` and pins all
    // ten digits to 0.70em, Readex Pro ignores it entirely. One declaration would align
    // half the site, so alignment stays inline-size — and the floor in `--num-cell` is
    // the widest single digit either face paints as rendered (0.712em at Montserrat 900).
    expect(globals).toMatch(/Montserrat has a `tnum` feature and Readex Pro has none/);
    expect(tokens).toMatch(/--num-cell:\s*max\(1ch, 0\.72em\)/);
    expect(globals).toMatch(
      /@utility num\s*\{[\s\S]*?min-inline-size:\s*calc\(var\(--num-digits, 1\)\s*\*\s*var\(--num-cell\)\);/,
    );
    // The declaration that only works on one of the two faces is gone from the tree, not
    // left behind as documentation of an intent nobody checked.
    const offenders = sourceFiles('src/components').filter((file) => /tabular-nums/.test(read(file)));
    expect(offenders).toEqual([]);
    // …and the faces themselves ask for no numeric feature.
    expect(siteFonts).not.toMatch(/font-feature-settings|font-variant-numeric/);
  });

  it('mirrors horizontal motion with the reading direction', () => {
    // Every file that animates along x has to say it knows which way the page runs —
    // a slide that enters from the right enters from the trailing edge in Arabic.
    const animated = sourceFiles().filter((file) =>
      /(?:initial|animate|exit|whileInView)=\{\{[^}]*\bx:/.test(read(file)),
    );
    expect(animated.length, 'the sweep would pass vacuously if nothing moved on x').toBeGreaterThan(0);
    for (const file of animated) {
      expect(
        read(file),
        `${file} slides without consulting the direction`,
      ).toMatch(/rtl|language === ['"]ar['"]|dir === ['"]rtl['"]/);
    }
  });

  it('gives the site sections no physical direction to inherit', () => {
    // The stylesheets are proved above; the components carry the same rule as classes.
    const physical =
      /(^|["'\s:])((m|p)(l|r)|left|right)-[a-z0-9[]|text-(left|right)\b|border-(l|r)-|rounded-(l|r)-|origin-(l|r)\b|space-x-/;
    const offenders = sourceFiles()
      .filter((file) => file.endsWith('.tsx'))
      .filter((file) => physical.test(withoutComments(read(file))));
    expect(offenders).toEqual([]);
    // Both halves of that pass have to be load-bearing: a sweep that matches nothing is
    // a sweep that stopped catching the class it was written for.
    expect(physical.test('className="flex items-center text-left"'), 'the rule still bites code').toBe(true);
    expect(physical.test(withoutComments('/** use text-left here */')), 'the rule skips prose').toBe(false);
  });
});
