/**
 * One-time provisioning of the local MariaDB instance (see docs/LOCAL-MARIADB.md).
 *
 * Refuses any host that is not loopback: this script mints passwords and writes them
 * to .env files, so it must never be pointed at a shared server.
 */
import { randomBytes } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import mysql from 'mysql2/promise';

const SOCKET_PATH = process.env.DATABASE_SOCKET?.trim();
const HOST = SOCKET_PATH ? (process.env.DATABASE_HOST ?? process.env.DB_HOST ?? 'localhost') : '127.0.0.1';
const PORT = Number(process.env.DATABASE_PORT ?? process.env.DB_PORT ?? 3307);
if (SOCKET_PATH && !['localhost', '127.0.0.1'].includes(HOST)) {
  throw new Error('Local provisioning only supports localhost or 127.0.0.1 when DATABASE_SOCKET is set.');
}
const ROOT_PASSWORD = process.env.LOCAL_DB_ROOT_PASSWORD ?? existingRootPassword();

function existingRootPassword() {
  try {
    return readFileSync(resolve('.env.local'), 'utf8').match(/^LOCAL_DB_ROOT_PASSWORD=(.*)$/m)?.[1] ?? '';
  } catch {
    return '';
  }
}

const passwords = {
  root: ROOT_PASSWORD || randomPassword(),
  app: randomPassword(),
  test: randomPassword(),
  sessionSecret: randomBytes(32).toString('hex'),
};

function randomPassword() {
  return randomBytes(18).toString('base64url');
}

const targets = [
  { db: 'shamah_cms', user: 'shamah_app', password: passwords.app },
  { db: 'shamah_cms_test', user: 'shamah_test', password: passwords.test },
];

const root = await mysql.createConnection({
  ...(SOCKET_PATH ? { socketPath: SOCKET_PATH } : { host: HOST, port: PORT }),
  user: 'root',
  password: ROOT_PASSWORD,
});

for (const t of targets) {
  await root.query(`CREATE DATABASE IF NOT EXISTS \`${t.db}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`);
  await root.query(`CREATE USER IF NOT EXISTS '${t.user}'@'${HOST}' IDENTIFIED BY '${t.password}'`);
  await root.query(`ALTER USER '${t.user}'@'${HOST}' IDENTIFIED BY '${t.password}'`);
  await root.query(`GRANT ALL PRIVILEGES ON \`${t.db}\`.* TO '${t.user}'@'${HOST}'`);
}

await root.query(`CREATE USER IF NOT EXISTS 'root'@'localhost' IDENTIFIED BY '${passwords.root}'`);
await root.query(`ALTER USER 'root'@'localhost' IDENTIFIED BY '${passwords.root}'`);
await root.query(`GRANT ALL PRIVILEGES ON *.* TO 'root'@'localhost' WITH GRANT OPTION`);
await root.query(`CREATE USER IF NOT EXISTS 'root'@'${HOST}' IDENTIFIED BY '${passwords.root}'`);
await root.query(`ALTER USER 'root'@'${HOST}' IDENTIFIED BY '${passwords.root}'`);
await root.query(`GRANT ALL PRIVILEGES ON *.* TO 'root'@'${HOST}' WITH GRANT OPTION`);
await root.query('FLUSH PRIVILEGES');
await root.end();

writeFileSync(
  resolve('.env.local'),
  envBlock({ db: 'shamah_cms', user: 'shamah_app', password: passwords.app }, passwords),
  'utf8',
);
writeFileSync(
  resolve('.env.test'),
  envBlock({ db: 'shamah_cms_test', user: 'shamah_test', password: passwords.test }, passwords),
  'utf8',
);

const names = [
  'DATABASE_HOST',
  'DATABASE_PORT',
  ...(SOCKET_PATH ? ['DATABASE_SOCKET'] : []),
  'DATABASE_NAME',
  'DATABASE_USER',
  'DATABASE_PASSWORD',
  'DATABASE_URL',
  'LOCAL_DB_ROOT_PASSWORD',
  'SESSION_SECRET',
];
console.log(`MariaDB provisioned on ${SOCKET_PATH || `${HOST}:${PORT}`}.`);
console.log(`Wrote .env.local (shamah_cms) and .env.test (shamah_cms_test) — variables: ${names.join(', ')}.`);
console.log('Values are in those files only; they are never printed here.');

function envBlock(target, secrets) {
  const url = `mysql://${target.user}:${target.password}@${HOST}:${PORT}/${target.db}`;
  return [
    '# Generated by scripts/db/provision-local.mjs — local loopback MariaDB only.',
    `DATABASE_HOST=${HOST}`,
    `DATABASE_PORT=${PORT}`,
    ...(SOCKET_PATH ? [`DATABASE_SOCKET=${SOCKET_PATH}`] : []),
    `DATABASE_NAME=${target.db}`,
    `DATABASE_USER=${target.user}`,
    `DATABASE_PASSWORD=${target.password}`,
    `DATABASE_URL=${url}`,
    `LOCAL_DB_ROOT_PASSWORD=${secrets.root}`,
    `SESSION_SECRET=${secrets.sessionSecret}`,
    '',
  ].join('\n');
}
